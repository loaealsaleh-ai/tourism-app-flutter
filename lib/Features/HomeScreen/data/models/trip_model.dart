class TripModel {
  final String title;
  final String location;
  final String image;
  final String duration;
  final String price;
  final double rating;
  final int reviews;

  const TripModel({
    required this.title,
    required this.location,
    required this.image,
    required this.duration,
    required this.price,
    required this.rating,
    required this.reviews,
  });
}
